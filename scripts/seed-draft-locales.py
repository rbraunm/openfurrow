def placeholdersIn(text):
  return {name for _, name, _, _ in Formatter().parse(text) if name}


def main():
  source = json.loads((localeDirectory / "en-US.json").read_text(encoding="utf-8"))
  sourceKeys = set(source["messages"])
  for locale, draft in (("es", es), ("fr", fr), ("ar", ar)):
    missing = sourceKeys - set(draft)
    extra = set(draft) - sourceKeys
    if missing or extra:
      raise SystemExit(f"{locale}: missing {sorted(missing)} extra {sorted(extra)}")
    for key, text in draft.items():
      expected = placeholdersIn(source["messages"][key]["text"])
      got = placeholdersIn(text)
      if expected != got:
        raise SystemExit(f"{locale}:{key}: placeholders {sorted(got)} != source {sorted(expected)}")
    document = {
      "locale": locale,
      "messages": {key: {"text": draft[key], "status": "machineDraft"} for key in sorted(draft)},
    }
    (localeDirectory / f"{locale}.json").write_text(
      json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{locale}: {len(draft)} messages, all machineDraft")


if __name__ == "__main__":
  main()
